#!/usr/bin/env bash
# bas-setup.sh - install Postgres, pinned Paperclip, systemd and off-box backups
# on the BAS automation server. Run from a workstation that can ssh to the box.
#
#   ./scripts/bas-setup.sh <ip-or-hostname>
#
# Ticket: LAC-4279. Runbook: docs/ops/bas-automation-server.md.
# Prerequisite: scripts/bas-provision.sh has run and cloud-init has finished.
#
# Safe to re-run. Every step is a no-op when already applied, except the
# Postgres password, which is only generated if /etc/paperclip/paperclip.env
# does not exist yet (regenerating it would orphan the existing database).
set -euo pipefail

HOST="${1:?usage: bas-setup.sh <ip-or-hostname>}"
SSH="ssh -o BatchMode=yes -o ConnectTimeout=20 -o StrictHostKeyChecking=accept-new root@$HOST"

# Pinned on purpose. The whole point of this box is that the version does not
# move on its own: zero's nightly auto-upgrade is the thing being removed here.
# Upgrades are deliberate and only after the version has run on zero for 3+ days.
# Keep this in sync with docs/ops/bas-automation-server.md (a test asserts it).
PAPERCLIP_VERSION="2026.1005.0"

OAUTH_TOKEN_FILE="${BAS_OAUTH_TOKEN_FILE:-$HOME/.paperclip/secrets/claude-oauth-token-hetzner}"
LIBRARY_IP="${BAS_LIBRARY_IP:-100.119.64.141}"
LIBRARY_DIR="${BAS_LIBRARY_DIR:-/mnt/user/backups/paperclip-bas}"

[ -r "$OAUTH_TOKEN_FILE" ] || { echo "no Max OAuth token at $OAUTH_TOKEN_FILE" >&2; exit 1; }

echo "==> 1/8 cloud-init finished?"
$SSH 'cloud-init status --wait >/dev/null 2>&1 || true; test -f /var/lib/cloud/bas-os-ready || { echo "cloud-init did not finish; see /var/log/cloud-init-output.log" >&2; exit 1; }; echo "os layer ready: $(. /etc/os-release; echo "$PRETTY_NAME"), node $(node -v), $(psql --version)"'

echo "==> 2/8 Postgres role + database"
# Password is generated on the box and never leaves it or appears in an argv.
$SSH 'set -e
  if [ ! -f /etc/paperclip/paperclip.env ]; then
    PW="$(openssl rand -hex 24)"
    su - postgres -c "psql -v ON_ERROR_STOP=1 -c \"DO \\\$\\\$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='"'"'paperclip'"'"') THEN CREATE ROLE paperclip LOGIN PASSWORD '"'"'$PW'"'"'; END IF; END \\\$\\\$;\""
    su - postgres -c "psql -tAc \"SELECT 1 FROM pg_database WHERE datname='"'"'paperclip'"'"'\"" | grep -q 1 \
      || su - postgres -c "createdb -O paperclip paperclip"
    install -d -m 0750 /etc/paperclip
    umask 027
    cat > /etc/paperclip/paperclip.env <<EOF
# Generated by scripts/bas-setup.sh (LAC-4279). Mode 0640 root:paperclip.
# DATABASE_URL is what makes Paperclip use this real Postgres instead of its
# bundled embedded one: dist/index.js does \`if (process.env.DATABASE_URL) return ...\`.
DATABASE_URL=postgres://paperclip:$PW@127.0.0.1:5432/paperclip
PORT=3100
HOST=127.0.0.1
# Backups are Paperclip'"'"'s own, so /api/health reports their age and the outside
# monitor on graphite can check it. Shipping them off the box is a separate timer.
PAPERCLIP_DB_BACKUP_ENABLED=true
PAPERCLIP_DB_BACKUP_DIR=/var/backups/paperclip
# Every 12h, not nightly. The outside monitor alarms at 26h, and a 1440 interval
# leaves only 2h of slack before one late run reads as a real failure. The off-box
# ship stays nightly, so it never carries a dump more than 12h old.
PAPERCLIP_DB_BACKUP_INTERVAL_MINUTES=720
PAPERCLIP_DB_BACKUP_RETENTION_DAYS=7
EOF
    chown root:paperclip /etc/paperclip/paperclip.env
    chmod 0640 /etc/paperclip/paperclip.env
    echo "created role, database and /etc/paperclip/paperclip.env"
  else
    echo "/etc/paperclip/paperclip.env already present; leaving the database alone"
  fi'

echo "==> 3/8 Max OAuth token"
# Piped over stdin so the token never appears in an argv, a log or user_data.
$SSH 'umask 077; cat > /etc/paperclip/oauth-token; chown root:paperclip /etc/paperclip/oauth-token; chmod 0640 /etc/paperclip/oauth-token; \
  grep -q "^CLAUDE_CODE_OAUTH_TOKEN=" /etc/paperclip/paperclip.env || printf "CLAUDE_CODE_OAUTH_TOKEN=%s\n" "$(cat /etc/paperclip/oauth-token)" >> /etc/paperclip/paperclip.env; \
  echo "token installed ($(wc -c < /etc/paperclip/oauth-token) bytes)"' < "$OAUTH_TOKEN_FILE"

echo "==> 4/8 pinned Paperclip $PAPERCLIP_VERSION"
$SSH "set -e
  have=\$(npm ls -g --depth=0 --json 2>/dev/null | jq -r '.dependencies.paperclipai.version // empty')
  if [ \"\$have\" = '$PAPERCLIP_VERSION' ]; then
    echo \"paperclipai $PAPERCLIP_VERSION already installed\"
  else
    echo \"installing paperclipai@$PAPERCLIP_VERSION (was: \${have:-none})\"
    npm install -g --no-fund --no-audit paperclipai@$PAPERCLIP_VERSION
  fi
  # No auto-upgrade job, by design. Assert that nothing has quietly added one.
  if ls /etc/cron.*/*paperclip* /etc/systemd/system/*paperclip*upgrade* >/dev/null 2>&1; then
    echo 'WARNING: something that looks like a Paperclip auto-upgrade job exists; this box is meant to be pinned' >&2
  fi"

echo "==> 4b/8 onboard, then point its config at the real Postgres"
# Two separate problems, both of which stop the box from working:
#
# 1. `paperclipai run` refuses to start with no config at all, and its onboarding
#    is interactive by default. These flags make it non-interactive and stop it
#    installing a service of its own, since systemd owns that here.
#
# 2. onboard always writes `database.mode: embedded-postgres`. The server itself
#    does honour DATABASE_URL over that, so it runs on the real database either
#    way, but leaving the two disagreeing is a trap worth closing:
#      - every CLI subcommand (db:backup, and so the restore path) reads the
#        config, not the env, so it dials the embedded port 54329 and fails;
#      - if DATABASE_URL ever went missing from the env, the server would quietly
#        start an embedded Postgres and come up as a brand-new EMPTY board while
#        the real data sat orphaned, and /api/health would report ok.
#    Setting mode=postgres makes that fail closed: no reachable database means no
#    start, which the monitor on graphite reports.
$SSH 'set -e
  if [ ! -f /var/lib/paperclip/.paperclip/instances/default/config.json ]; then
    su - paperclip -s /bin/bash -c "paperclipai onboard -y --bind loopback --no-install-service" >/dev/null
    echo "onboarded"
  else
    echo "already onboarded"
  fi
  C=/var/lib/paperclip/.paperclip/instances/default/config.json
  DB_URL=$(sed -n "s/^DATABASE_URL=//p" /etc/paperclip/paperclip.env)
  [ -n "$DB_URL" ] || { echo "no DATABASE_URL in /etc/paperclip/paperclip.env" >&2; exit 1; }
  # $meta.source is a strict enum ("onboard"|"configure"|"doctor"). Anything else
  # makes paperclip doctor fail and the service refuse to boot.
  jq --arg u "$DB_URL" "
      .database.mode = \"postgres\"
    | .database.connectionString = \$u
    | .database.backup.dir = \"/var/backups/paperclip\"
    | .database.backup.intervalMinutes = 720
    | .database.backup.retentionDays = 7
    | .\"\$meta\".source = \"configure\"
  " "$C" > "$C.new"
  chown paperclip:paperclip "$C.new"; chmod 0600 "$C.new"; mv "$C.new" "$C"
  jq -c "{mode:.database.mode, backup:.database.backup}" "$C"'

echo "==> 5/8 systemd unit"
$SSH "cat > /etc/systemd/system/paperclip.service <<'UNIT'
[Unit]
Description=Paperclip control plane (Build and Serve automations, pinned)
Documentation=https://github.com/lacymorrow/buildandserve/blob/main/docs/ops/bas-automation-server.md
After=network-online.target postgresql.service
Wants=network-online.target
Requires=postgresql.service
# A boot-loop must not hammer Postgres forever: 5 starts in 5 min, then stop and
# let the outside monitor on graphite report it, rather than spinning silently.
# These are [Unit] options. systemd ignores them under [Service] with only a log
# line ('Unknown key name ... in section Service, ignoring'), which is how the
# first version of this unit shipped with no crash-loop guard at all.
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=simple
User=paperclip
Group=paperclip
WorkingDirectory=/var/lib/paperclip
EnvironmentFile=/etc/paperclip/paperclip.env
ExecStart=/usr/bin/paperclipai run
# A killed process has to come back without anyone noticing it died.
Restart=always
RestartSec=5
# Log to the journal, which is capped in cloud-init. Nothing writes an
# unrotated server.log here: that file reached 2 GB on zero.
StandardOutput=journal
StandardError=journal
SyslogIdentifier=paperclip
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ProtectHome=read-only
ReadWritePaths=/var/lib/paperclip /var/backups/paperclip

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable paperclip.service >/dev/null
echo 'paperclip.service installed (Restart=always)'"

echo "==> 6/8 off-box backup shipping"
# Paperclip writes the dumps; this only moves the newest one to the library NAS
# over Tailscale and prunes the far end. Same shape as graphite's section 1a.
$SSH "set -e
  cat > /usr/local/bin/bas-ship-backup.sh <<'SHIP'
#!/usr/bin/env bash
# Ship the newest Paperclip dump to the library NAS. Installed by bas-setup.sh (LAC-4279).
# A backup that only exists on the box it is backing up is not a backup.
set -uo pipefail
SRC_DIR=/var/backups/paperclip
DEST_HOST=root@$LIBRARY_IP
DEST_DIR=$LIBRARY_DIR
KEY=/etc/paperclip/library_backup_ed25519
SSH_OPTS=\"-i \$KEY -o BatchMode=yes -o ConnectTimeout=25 -o StrictHostKeyChecking=accept-new\"
newest=\$(ls -t \"\$SRC_DIR\"/*.sql.gz \"\$SRC_DIR\"/*.dump 2>/dev/null | head -1)
[ -n \"\$newest\" ] || { echo \"no dump in \$SRC_DIR yet\"; exit 1; }
ssh \$SSH_OPTS \"\$DEST_HOST\" \"mkdir -p '\$DEST_DIR'\" || exit 1
rsync -a --partial -e \"ssh \$SSH_OPTS\" \"\$newest\" \"\$DEST_HOST:\$DEST_DIR/\" || exit 1
# Retain 14, pruned on the NAS so a dead tunnel cannot leave it unpruned.
ssh \$SSH_OPTS \"\$DEST_HOST\" \"cd '\$DEST_DIR' && ls -t 2>/dev/null | tail -n +15 | while read -r f; do rm -f -- \\\"\\\$f\\\"; done; chown -R 99:100 '\$DEST_DIR'\" || true
echo \"shipped \$(basename \"\$newest\") to \$DEST_DIR\"
SHIP
  chmod 0755 /usr/local/bin/bas-ship-backup.sh

  if [ ! -f /etc/paperclip/library_backup_ed25519 ]; then
    ssh-keygen -t ed25519 -N '' -C 'bas-ship-backup' -f /etc/paperclip/library_backup_ed25519 >/dev/null
    echo 'generated a backup ssh key; its public half still needs adding to the NAS (step 7)'
  fi

  cat > /etc/systemd/system/bas-ship-backup.service <<'SVC'
[Unit]
Description=Ship newest Paperclip DB dump to the library NAS
After=network-online.target

[Service]
Type=oneshot
ExecStart=/usr/local/bin/bas-ship-backup.sh
SVC
  cat > /etc/systemd/system/bas-ship-backup.timer <<'TMR'
[Unit]
Description=Nightly off-box Paperclip backup

[Timer]
OnCalendar=03:30
RandomizedDelaySec=15m
# Catch up after a reboot instead of silently skipping a night.
Persistent=true

[Install]
WantedBy=timers.target
TMR
  systemctl daemon-reload
  # --now matters: plain 'enable' leaves the timer inactive until the next boot,
  # so the off-box copy silently never happens. That shipped once; 'systemctl
  # list-timers' showed zero timers on a box whose timer was 'enabled'.
  systemctl enable --now bas-ship-backup.timer >/dev/null
  echo 'bas-ship-backup.timer installed (nightly 03:30)'"

echo "==> 6b/8 job freshness probe (read by graphite's fleet-health over ssh)"
# A control plane that answers /api/health while every client job silently fails
# is the outage we actually fear, so job freshness is checked separately from
# liveness. The query lives here, on the box, so the monitor on graphite does not
# have to carry SQL through two layers of shell quoting; graphite only reads the
# output and decides. If the box is dead, graphite's ssh fails and that is the alarm.
$SSH "cat > /usr/local/bin/bas-job-freshness.sh <<'PROBE'
#!/usr/bin/env bash
# Print 'routine title|hours since last successful run' for every active routine.
# 'never' means it has never completed once. Installed by bas-setup.sh (LAC-4279).
set -uo pipefail
exec su - postgres -c \"psql -d paperclip -At -F'|' -v ON_ERROR_STOP=1 <<'SQL'
select r.title,
       coalesce(round(extract(epoch from (now() - max(rr.completed_at) filter (where rr.status='completed')))/3600)::text, 'never')
from routines r
left join routine_runs rr on rr.routine_id = r.id
where r.status = 'active'
group by r.title
order by 1;
SQL
\"
PROBE
chmod 0755 /usr/local/bin/bas-job-freshness.sh
echo 'bas-job-freshness.sh installed'"

echo "==> 7/8 public key for the NAS (add this to library:/root/.ssh/authorized_keys)"
$SSH 'cat /etc/paperclip/library_backup_ed25519.pub'

echo "==> 8/8 start, and prove which Postgres it actually used"
$SSH 'set -e
  systemctl restart paperclip.service
  for _ in $(seq 60); do
    curl -fsS -m 5 http://127.0.0.1:3100/api/health >/dev/null 2>&1 && break
    sleep 2
  done
  echo "--- /api/health ---"
  curl -fsS -m 10 http://127.0.0.1:3100/api/health | jq "{status, databaseBackup}" || { journalctl -u paperclip -n 40 --no-pager; exit 1; }
  # The ticket asks for a real Postgres, not the embedded one. Prove it rather
  # than assume it: our database must hold the schema, and the embedded
  # Postgres port must not be listening.
  echo "--- which database ---"
  n=$(su - postgres -c "psql -tAc \"SELECT count(*) FROM information_schema.tables WHERE table_schema='"'"'public'"'"'\" paperclip")
  echo "tables in the paperclip database: $n"
  [ "$n" -gt 0 ] || { echo "FAIL: our Postgres is empty, so Paperclip came up on its embedded database; check DATABASE_URL in /etc/paperclip/paperclip.env" >&2; exit 1; }
  ss -lntp 2>/dev/null | grep -E ":(54329|5432)\b" || true
  # Take the first backup now. The scheduler only fires every 12h, so without
  # this the box spends its first half day with no backup at all, which the
  # outside monitor correctly reports as a failure the moment it is switched on.
  echo "--- first backup ---"
  if ls /var/backups/paperclip/*.sql.gz >/dev/null 2>&1; then
    echo "a dump already exists: $(ls -t /var/backups/paperclip/*.sql.gz | head -1)"
  else
    # The CLI needs the env passed in explicitly, because /etc/paperclip is
    # root-only and this has to run as the paperclip user.
    systemd-run --uid=paperclip --property=EnvironmentFile=/etc/paperclip/paperclip.env \
      --property=WorkingDirectory=/var/lib/paperclip --wait --pipe --quiet \
      /usr/bin/paperclipai db:backup 2>&1 | tail -2
  fi
  ls -la /var/backups/paperclip/
  echo "--- off-box timer is actually running ---"
  systemctl is-active bas-ship-backup.timer
  systemctl list-timers bas-ship-backup.timer --no-pager | head -2'

cat <<EOF

done. remaining, by hand (runbook: docs/ops/bas-automation-server.md):
  - add the public key above to library:/root/.ssh/authorized_keys, then:
      ssh root@$HOST systemctl start bas-ship-backup.service
  - expose it on the tailnet (no public port):
      ssh root@$HOST 'tailscale serve --bg https / http://127.0.0.1:3100'
  - then from graphite: curl https://bas.hyrax-boga.ts.net/api/health
EOF
